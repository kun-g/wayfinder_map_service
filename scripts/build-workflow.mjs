import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const sourcePath = resolve(root, 'docs/agents/exploration-mcp.md');
export const outputPath = resolve(root, 'src/workflow.generated.ts');
const toolNames = ['map_create', 'map_list', 'map_read', 'map_apply'];
const blockNames = ['safety-core', 'instructions-summary', ...toolNames.map(name => `tool:${name}`), 'prompt'];

function compareSemVer(left, right) {
  const a = left.split('.').map(Number);
  const b = right.split('.').map(Number);
  for (let index = 0; index < 3; index++) {
    if (a[index] !== b[index]) return a[index] - b[index];
  }
  return 0;
}

function fail(message) { throw new Error(`Workflow build refused: ${message}`); }

export function parseWorkflow(markdown, previousMarkdown) {
  const versionMatches = [...markdown.matchAll(/^workflowVersion: ([^\s]+)$/gm)];
  if (versionMatches.length !== 1 || !/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(versionMatches[0]?.[1] ?? '')) {
    fail('exactly one valid SemVer workflowVersion is required');
  }
  const workflowVersion = versionMatches[0][1];
  const blocks = {};
  let priorEnd = -1;
  for (const name of blockNames) {
    const startMarker = `<!-- wayfinder:${name}:start -->`;
    const endMarker = `<!-- wayfinder:${name}:end -->`;
    const starts = markdown.split(startMarker).length - 1;
    const ends = markdown.split(endMarker).length - 1;
    if (starts !== 1 || ends !== 1) fail(`block ${name} must have one start and one end marker`);
    const start = markdown.indexOf(startMarker);
    const contentStart = start + startMarker.length;
    const end = markdown.indexOf(endMarker, contentStart);
    if (start <= priorEnd || end < contentStart) fail(`block ${name} is missing or out of order`);
    const content = markdown.slice(contentStart, end).trim();
    if (!content) fail(`block ${name} is empty`);
    blocks[name] = content;
    priorEnd = end + endMarker.length;
  }
  const discoveredTools = [...markdown.matchAll(/<!-- wayfinder:tool:([^:]+):start -->/g)].map(match => match[1]);
  if (JSON.stringify(discoveredTools) !== JSON.stringify(toolNames)) fail('business tool blocks must be exactly the accepted four in order');
  const safetyCore = blocks['safety-core'];
  if ([...safetyCore].length > 512) fail('safety core exceeds 512 characters');
  for (const required of ['alone owns Map state', 'fully page `map_list`', 'create once', 'resume or uncertainty',
    'returned Frontier Ticket', 'latest observed Revision', 'On conflict, reread, report, and stop',
    'old request is void', 'human sees the new Revision and issues a new request', 'Never replay, merge, or take over',
    'live human verdict']) {
    if (!safetyCore.includes(required)) fail(`safety core omits required rule: ${required}`);
  }
  if (previousMarkdown !== undefined) {
    const previous = parseWorkflow(previousMarkdown);
    const changed = markdown !== previousMarkdown;
    const comparison = compareSemVer(workflowVersion, previous.workflowVersion);
    if (changed && comparison <= 0) fail('changed workflow must increase workflowVersion');
    if (!changed && comparison !== 0) fail('unchanged workflow cannot claim a different version');
  }
  const instructions = `${safetyCore}\n\nworkflowVersion: ${workflowVersion}\n\n${blocks['instructions-summary']}`;
  return { workflowVersion, markdown, safetyCore, instructions,
    toolDescriptions: Object.fromEntries(toolNames.map(name => [name, blocks[`tool:${name}`]])), prompt: blocks.prompt };
}

function committedSource() {
  try {
    const source = execFileSync('git', ['show', 'HEAD:docs/agents/exploration-mcp.md'], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
    return /^workflowVersion: /m.test(source) ? source : undefined;
  } catch { return undefined; }
}

export function buildWorkflow(markdown = readFileSync(sourcePath, 'utf8'), previousMarkdown = committedSource()) {
  const contract = parseWorkflow(markdown, previousMarkdown);
  const generated = `// Generated by scripts/build-workflow.mjs from docs/agents/exploration-mcp.md. Do not edit.\n`
    + `export const workflowContract = Object.freeze(${JSON.stringify(contract, null, 2)} as const);\n`;
  writeFileSync(outputPath, generated, { encoding: 'utf8', mode: 0o600 });
  return contract;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { buildWorkflow(); }
  catch (error) { console.error(error instanceof Error ? error.message : 'Workflow build refused'); process.exitCode = 1; }
}
